#!/usr/bin/env python3
"""Bundle the genesis package into ONE self-contained Kaggle script (paste into a notebook cell or run as a script).
Each Kaggle session runs an independent island with its own seed; pull runs/kaggle_*/ckpt.pkl back and merge."""
import os, base64, io, tarfile
here = os.path.dirname(os.path.abspath(__file__)); buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as t:
    t.add(os.path.join(here, "genesis"), "genesis", filter=lambda x: None if "__pycache__" in x.name else x)
    t.add(os.path.join(here, "run_box.py"), "run_box.py")
b = base64.b64encode(buf.getvalue()).decode()
src = f'''# GENESIS Kaggle island worker (auto-generated by make_kaggle.py). CPU numpy; uses all Kaggle cores.
import base64, io, tarfile, os, subprocess, sys
os.makedirs("/kaggle/working/genesis-search", exist_ok=True); os.chdir("/kaggle/working/genesis-search")
tarfile.open(fileobj=io.BytesIO(base64.b64decode("{b}")), mode="r:gz").extractall(".")
SEED = int(os.environ.get("GENESIS_SEED", "101")); MIN = os.environ.get("GENESIS_MINUTES", "500")
subprocess.run([sys.executable, "run_box.py", "--minutes", MIN, "--seed", str(SEED), "--out", f"runs/kaggle_{{SEED}}"], check=True)
'''
os.makedirs(os.path.join(here, "kaggle"), exist_ok=True)
open(os.path.join(here, "kaggle", "genesis_kaggle.py"), "w").write(src)
import json
nb = {"cells": [{"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": src.splitlines(True)}],
      "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"}}, "nbformat": 4, "nbformat_minor": 5}
json.dump(nb, open(os.path.join(here, "kaggle", "genesis_kaggle.ipynb"), "w"))
print("wrote kaggle/genesis_kaggle.py and .ipynb", len(src), "bytes")
